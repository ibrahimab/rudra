/// Provides safe text operations for Rudra's terminal renderers.
///
/// Filesystem paths, entry names, and inspection diagnostics
/// may contain untrusted text.
///
/// This utility provides:
/// - Removal of terminal control behavior.
/// - Approximate Unicode display-column measurement.
/// - Width-aware truncation.
/// - Width-aware left and right padding.
///
/// These operations apply to unstyled content before a rendering
/// backend adds ANSI sequences or framework-specific styles.
///
/// Unicode width is an approximation. Combining marks and common
/// wide-character ranges are handled, but complex grapheme
/// clusters, emoji sequences, and terminal-specific width rules
/// may produce different physical widths.
///
/// Rendering backends requiring exact terminal layout should
/// use a dedicated, tested Unicode layout implementation.
///
/// No terminal I/O, filesystem access, or SDK calls occur.
///
/// Example:
/// ```dart
/// final safe = TerminalText.sanitize('hello\x1B[31m');
///
/// final clipped = TerminalText.truncate(
///   'very-long-filename.txt',
///   max_columns: 12,
/// );
///
/// print(safe);
/// print(clipped);
/// ```
final class TerminalText {
  /// Prevents construction of this static utility class.
  TerminalText._();

  /// Replaces unsafe control characters in untrusted text.
  ///
  /// The following characters are replaced with '?'.
  ///
  /// - ASCII C0 controls, including ESC, CR, LF, and TAB.
  /// - DEL and C1 control characters.
  /// - Unicode bidirectional formatting controls.
  /// - Unicode paragraph and line separators.
  /// - The Unicode byte-order mark.
  ///
  /// Replacing ESC and C1 controls prevents untrusted text
  /// from introducing ANSI control sequences.
  ///
  /// Replacing bidirectional formatting controls prevents
  /// those controls from visually reordering surrounding
  /// terminal content.
  ///
  /// Ordinary Unicode characters are preserved.
  ///
  /// The original string is not modified.
  ///
  /// This function must be applied to content before ANSI
  /// styling is generated by the renderer.
  ///
  /// Example:
  /// ```dart
  /// final safe = TerminalText.sanitize('a\nb');
  ///
  /// print(safe);
  /// // a?b
  /// ```
  static String sanitize(String value) {
    final result = StringBuffer();

    for (final code_point in value.runes) {
      if (_is_unsafe(code_point)) {
        result.write('?');
      } else {
        result.writeCharCode(code_point);
      }
    }

    return result.toString();
  }

  /// Estimates the number of terminal columns occupied by text.
  ///
  /// The supplied text is sanitized before measurement.
  ///
  /// Most printable characters occupy one column.
  /// Common East Asian wide characters and emoji occupy two.
  /// Recognized combining marks occupy zero additional columns.
  ///
  /// This estimate is suitable for the initial bare renderer,
  /// but does not implement complete Unicode grapheme-cluster
  /// segmentation or every terminal's width conventions.
  ///
  /// In particular, joined emoji sequences may be counted
  /// conservatively as multiple wide characters.
  ///
  /// Applications must not use this estimate for security
  /// decisions, filesystem identity, or path comparisons.
  ///
  /// Example:
  /// ```dart
  /// print(TerminalText.estimated_columns('abc'));
  /// // 3
  ///
  /// print(TerminalText.estimated_columns('文件'));
  /// // 4
  /// ```
  static int estimated_columns(String value) {
    final safe = sanitize(value);

    var columns = 0;

    for (final code_point in safe.runes) {
      columns += _code_point_columns(code_point);
    }

    return columns;
  }

  /// Truncates text to approximately [max_columns].
  ///
  /// The input is sanitized before processing.
  ///
  /// Text that fits is returned without an ellipsis.
  ///
  /// Text requiring truncation receives a trailing Unicode
  /// ellipsis, which occupies one estimated column.
  ///
  /// A zero-width limit returns an empty string.
  ///
  /// Truncation occurs at Unicode code-point boundaries.
  /// It never splits a UTF-16 surrogate pair.
  ///
  /// It does not guarantee preservation of entire grapheme
  /// clusters, such as joined emoji sequences. This limitation
  /// belongs to the initial bare renderer's width approximation.
  ///
  /// Throws [ArgumentError] for a negative width.
  ///
  /// Example:
  /// ```dart
  /// final result = TerminalText.truncate(
  ///   'abcdefghij',
  ///   max_columns: 6,
  /// );
  ///
  /// print(result);
  /// // abcde…
  /// ```
  static String truncate(String value, {required int max_columns}) {
    _validate_columns(max_columns, 'max_columns');

    if (max_columns == 0) {
      return '';
    }

    final safe = sanitize(value);

    if (estimated_columns(safe) <= max_columns) {
      return safe;
    }

    const ellipsis = '…';
    const ellipsis_columns = 1;

    final available_columns = max_columns - ellipsis_columns;

    final result = StringBuffer();
    var used_columns = 0;

    for (final code_point in safe.runes) {
      final character_columns = _code_point_columns(code_point);

      if (used_columns + character_columns > available_columns) {
        break;
      }

      result.writeCharCode(code_point);
      used_columns += character_columns;
    }

    result.write(ellipsis);

    return result.toString();
  }

  /// Pads text on the right to an estimated terminal width.
  ///
  /// Sanitizes the supplied text and adds ordinary ASCII spaces.
  ///
  /// If the text already occupies at least [min_columns],
  /// it is returned without additional padding or truncation.
  ///
  /// Throws [ArgumentError] for a negative width.
  ///
  /// Example:
  /// ```dart
  /// final result = TerminalText.pad_right(
  ///   'DIR',
  ///   min_columns: 6,
  /// );
  ///
  /// print('$result|');
  /// // DIR   |
  /// ```
  static String pad_right(String value, {required int min_columns}) {
    _validate_columns(min_columns, 'min_columns');

    final safe = sanitize(value);
    final width = estimated_columns(safe);

    if (width >= min_columns) {
      return safe;
    }

    return safe.padRight(safe.length + min_columns - width);
  }

  /// Pads text on the left to an estimated terminal width.
  ///
  /// Sanitizes the supplied text and adds ordinary ASCII spaces.
  ///
  /// If the text already occupies at least [min_columns],
  /// it is returned unchanged.
  ///
  /// Throws [ArgumentError] for a negative width.
  ///
  /// Example:
  /// ```dart
  /// final result = TerminalText.pad_left(
  ///   '42',
  ///   min_columns: 5,
  /// );
  ///
  /// print('|$result');
  /// // |   42
  /// ```
  static String pad_left(String value, {required int min_columns}) {
    _validate_columns(min_columns, 'min_columns');

    final safe = sanitize(value);
    final width = estimated_columns(safe);

    if (width >= min_columns) {
      return safe;
    }

    return safe.padLeft(safe.length + min_columns - width);
  }

  /// Rejects negative terminal column counts.
  ///
  /// Zero is valid for truncation and padding operations.
  static void _validate_columns(int columns, String parameter_name) {
    if (columns < 0) {
      throw ArgumentError.value(
        columns,
        parameter_name,
        'Terminal column count cannot be negative.',
      );
    }
  }

  /// Identifies characters unsafe for terminal presentation.
  ///
  /// These are Unicode control or formatting code points
  /// that may affect terminal behavior or visual ordering.
  static bool _is_unsafe(int code_point) {
    // ASCII controls, DEL, and C1 controls.
    if (code_point <= 0x1F || (code_point >= 0x7F && code_point <= 0x9F)) {
      return true;
    }

    // Arabic letter mark and left/right direction marks.
    if (code_point == 0x061C || code_point == 0x200E || code_point == 0x200F) {
      return true;
    }

    // Bidirectional embeddings, overrides, and isolates.
    if ((code_point >= 0x202A && code_point <= 0x202E) ||
        (code_point >= 0x2066 && code_point <= 0x2069)) {
      return true;
    }

    // Unicode line/paragraph separators and byte-order mark.
    if (code_point == 0x2028 || code_point == 0x2029 || code_point == 0xFEFF) {
      return true;
    }

    return false;
  }

  /// Estimates the terminal width of one Unicode code point.
  ///
  /// Zero-width combining and formatting characters do not
  /// increase the estimated column count.
  ///
  /// Common wide-character ranges consume two columns.
  ///
  /// Other printable characters consume one column.
  ///
  /// These rules deliberately approximate terminal behavior
  /// rather than implement a complete Unicode width database.
  static int _code_point_columns(int code_point) {
    if (_is_zero_width(code_point)) {
      return 0;
    }

    if (_is_wide(code_point)) {
      return 2;
    }

    return 1;
  }

  /// Recognizes common Unicode combining and zero-width ranges.
  ///
  /// The included ranges cover combining diacritics,
  /// variation selectors, emoji modifiers, and joiners.
  static bool _is_zero_width(int code_point) {
    return (code_point >= 0x0300 && code_point <= 0x036F) ||
        (code_point >= 0x1AB0 && code_point <= 0x1AFF) ||
        (code_point >= 0x1DC0 && code_point <= 0x1DFF) ||
        (code_point >= 0x20D0 && code_point <= 0x20FF) ||
        (code_point >= 0xFE20 && code_point <= 0xFE2F) ||
        (code_point >= 0xFE00 && code_point <= 0xFE0F) ||
        (code_point >= 0xE0100 && code_point <= 0xE01EF) ||
        (code_point >= 0x1F3FB && code_point <= 0x1F3FF) ||
        code_point == 0x200C ||
        code_point == 0x200D;
  }

  /// Recognizes common two-column Unicode characters.
  ///
  /// Covers major East Asian full-width ranges and common
  /// emoji blocks.
  ///
  /// This is not a complete Unicode East Asian Width table.
  /// Additional coverage should come from a maintained Unicode
  /// implementation rather than indefinitely extending this list.
  static bool _is_wide(int code_point) {
    return (code_point >= 0x1100 && code_point <= 0x115F) ||
        (code_point >= 0x2329 && code_point <= 0x232A) ||
        (code_point >= 0x2E80 && code_point <= 0xA4CF) ||
        (code_point >= 0xAC00 && code_point <= 0xD7A3) ||
        (code_point >= 0xF900 && code_point <= 0xFAFF) ||
        (code_point >= 0xFE10 && code_point <= 0xFE19) ||
        (code_point >= 0xFE30 && code_point <= 0xFE6F) ||
        (code_point >= 0xFF00 && code_point <= 0xFF60) ||
        (code_point >= 0xFFE0 && code_point <= 0xFFE6) ||
        (code_point >= 0x1F300 && code_point <= 0x1FAFF) ||
        (code_point >= 0x20000 && code_point <= 0x3FFFD);
  }
}
